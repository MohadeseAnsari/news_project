def classify(name: str) -> tuple[str, bool]:
    """
    رشته را به دسته نگاشت می‌کند.
    Returns: (category_name, is_ambiguous)
    """
    name = name.strip()
    for pattern, category in RULES:
        if re.search(pattern, name):
            return category, False
    return "other", True


def main():
    # ۱. خواندن فایل xlsx
    if not XLSX_FILE.exists():
        print(f" فایل پیدا نشد: {XLSX_FILE}")
        print("لطفاً فایل fields.xlsx را در پوشه data/ قرار دهید.")
        return

    wb = openpyxl.load_workbook(XLSX_FILE)
    ws = wb.active

    # ۲. استخراج رشته‌ها (از ردیف ۲، چون ردیف ۱ سرصفحه است)
    fields = []
    for row in ws.iter_rows(min_row=2, values_only=True):
        if row[0] and str(row[0]).strip():
            fields.append(str(row[0]).strip())

    print("=" * 60)
    print(f" تعداد کل ردیف‌های ورودی: {len(fields)}")

    # ۳. حذف تکراری‌ها با حفظ ترتیب
    unique_fields = list(dict.fromkeys(fields))
    duplicates = len(fields) - len(unique_fields)
    print(f" تعداد تکراری‌ها: {duplicates}")
    print(f" تعداد رشته‌های یونیک: {len(unique_fields)}")
    print("=" * 60)

    # ۴. نگاشت
    rows = []
    counts = {}
    ambiguous = []

    for f in unique_fields:
        cat, is_amb = classify(f)
        rows.append({
            "field_name": f,
            "category_name": cat,
            "is_ambiguous": "yes" if is_amb else "no",
        })
        counts[cat] = counts.get(cat, 0) + 1
        if is_amb:
            ambiguous.append(f)

    # ۵. ذخیره CSV
    with CSV_OUTPUT.open("w", encoding="utf-8-sig", newline="") as fp:
        writer = csv.DictWriter(
            fp,
            fieldnames=["field_name", "category_name", "is_ambiguous"],
        )
        writer.writeheader()
        writer.writerows(rows)

    # ۶. گزارش
    print(f"\n ذخیره شد: {CSV_OUTPUT}")
    print("\n توزیع دسته‌ها:")
    print("-" * 60)
    for cat, cnt in sorted(counts.items(), key=lambda x: -x[1]):
        pct = (cnt / len(unique_fields)) * 100
        print(f"  {cat:22s} {cnt:4d}  ({pct:5.1f}%)")
    print("-" * 60)

    if ambiguous:
        print(f"\n  رشته‌های بدون نگاشت (other): {len(ambiguous)}")
        print("-" * 60)
        for f in ambiguous:
            print(f"  - {f}")
    else:
        print("\n هیچ رشته‌ای بدون نگاشت نماند!")


if __name__ == "__main__":
    main()
